'use strict';

/**
 * Generates src/sql/sql-catalog.ts from:
 *   - docs/specs/catalogs/sql-keywords.json
 *   - docs/specs/catalogs/builtin-functions.json
 *
 * Keeps runtime SQL/SQLScript IntelliSense 100% dependency-free (pure TypeScript).
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const KEYWORDS_PATH = path.join(ROOT, 'docs', 'specs', 'catalogs', 'sql-keywords.json');
const FUNCTIONS_PATH = path.join(ROOT, 'docs', 'specs', 'catalogs', 'builtin-functions.json');
const TS_OUT_PATH = path.join(ROOT, 'src', 'sql', 'sql-catalog.ts');

const SQL_BUILT_IN_LIBRARIES = [
  {
    name: 'SQLSCRIPT_SYNC',
    fullName: 'SYS.SQLSCRIPT_SYNC',
    description: 'Built-in SQLScript synchronization library (SLEEP_SECONDS, WAIT_SECONDS, mutex/barrier helpers) ([XSA]/[HDI]/[CLOUD]).',
  },
  {
    name: 'SQLSCRIPT_STRING',
    fullName: 'SYS.SQLSCRIPT_STRING',
    description: 'Built-in SQLScript string formatting, splitting, and table summary library ([XSC]/[XSA]/[HDI]/[CLOUD]).',
  },
  {
    name: 'SQLSCRIPT_PRINT',
    fullName: 'SYS.SQLSCRIPT_PRINT',
    description: 'Built-in SQLScript console print helpers (PRINT_LINE, PRINT_TABLE) ([XSC]/[XSA]/[HDI]/[CLOUD]).',
  },
  {
    name: 'SQLSCRIPT_LOGGING',
    fullName: 'SYS.SQLSCRIPT_LOGGING',
    description: 'Built-in SQLScript structured logging configuration and log writer library ([XSA]/[HDI]/[CLOUD]).',
  },
  {
    name: 'SQLSCRIPT_TEST',
    fullName: 'SYS.SQLSCRIPT_TEST',
    description: 'Built-in SQLScript unit testing assertions and discovery helpers ([XSA]/[HDI]/[CLOUD]).',
  },
];

function classifyKeywordKind(scope) {
  if (scope === 'storage.type.hanasql') return 'type';
  if (scope === 'support.variable.system.hanasql') return 'sysvar';
  if (scope.includes('pragma')) return 'pragma';
  if (scope.startsWith('support.constant.') || scope.startsWith('constant.')) return 'constant';
  if (scope.startsWith('support.function.')) return 'function';
  return 'keyword';
}

function buildSqlCatalogTs() {
  const kwRaw = JSON.parse(fs.readFileSync(KEYWORDS_PATH, 'utf8'));
  const fnRaw = JSON.parse(fs.readFileSync(FUNCTIONS_PATH, 'utf8'));

  const keywords = (kwRaw.keywords || [])
    .map((k) => ({
      name: k.name,
      kind: classifyKeywordKind(k.scope || ''),
      category: k.category || 'non-reserved',
      scope: k.scope || 'keyword.other.hanasql',
      platforms: Array.isArray(k.platforms) ? k.platforms : ['XSC', 'XSA', 'HDI', 'CLOUD'],
    }))
    .sort((a, b) => a.name.localeCompare(b.name));

  const keywordMap = {};
  const systemVariables = [];
  for (const k of keywords) {
    keywordMap[k.name] = k;
    if (k.kind === 'sysvar') {
      systemVariables.push(k);
    }
  }

  const libraryNames = new Set(SQL_BUILT_IN_LIBRARIES.map((l) => l.name));
  const globalFunctions = [];
  const libraryMembers = {};
  for (const libName of libraryNames) {
    libraryMembers[libName] = [];
  }

  for (const f of fnRaw.functions || []) {
    const sigs = Array.isArray(f.signatures) ? f.signatures : [f.name];
    const isConstant = sigs.length > 0 && (/CONSTANT\b/i.test(sigs[0]) || !sigs[0].includes('('));
    const entry = {
      name: f.name,
      library: f.library || 'SYS',
      signatures: sigs,
      returnType: f.returnType || 'ANY',
      description: f.description || '',
      ...(isConstant ? { isConstant: true } : {}),
      ...(f.name.startsWith('CE_') ? { deprecatedInCloud: true } : {}),
    };

    if (libraryNames.has(entry.library)) {
      libraryMembers[entry.library].push(entry);
    } else {
      globalFunctions.push(entry);
    }
  }

  globalFunctions.sort((a, b) => a.name.localeCompare(b.name));
  for (const libName of Object.keys(libraryMembers)) {
    libraryMembers[libName].sort((a, b) => a.name.localeCompare(b.name));
  }

  const header =
    '// Generated by scripts/build-sql-catalog.js from docs/specs/catalogs/\n' +
    '// (sql-keywords.json + builtin-functions.json). Do not hand-edit; run: npm run build:keywords\n\n' +
    "export type SqlKeywordKind = 'keyword' | 'type' | 'constant' | 'sysvar' | 'pragma' | 'function';\n\n" +
    'export interface SqlKeywordEntry {\n' +
    '  readonly name: string;\n' +
    '  readonly kind: SqlKeywordKind;\n' +
    '  readonly category: string;\n' +
    '  readonly scope: string;\n' +
    '  readonly platforms: readonly string[];\n' +
    '}\n\n' +
    'export interface SqlFunctionEntry {\n' +
    '  readonly name: string;\n' +
    '  readonly library: string;\n' +
    '  readonly signatures: readonly string[];\n' +
    '  readonly returnType: string;\n' +
    '  readonly description: string;\n' +
    '  readonly isConstant?: boolean;\n' +
    '  readonly deprecatedInCloud?: boolean;\n' +
    '}\n\n' +
    'export interface SqlBuiltinLibraryInfo {\n' +
    '  readonly name: string;\n' +
    '  readonly fullName: string;\n' +
    '  readonly description: string;\n' +
    '}\n\n';

  return (
    header +
    `export const SQL_BUILT_IN_LIBRARIES: readonly SqlBuiltinLibraryInfo[] = ${JSON.stringify(SQL_BUILT_IN_LIBRARIES, null, 2)};\n\n` +
    `export const SQL_KEYWORD_ENTRIES: readonly SqlKeywordEntry[] = ${JSON.stringify(keywords, null, 2)};\n\n` +
    `export const SQL_KEYWORDS_MAP: Readonly<Record<string, SqlKeywordEntry>> = ${JSON.stringify(keywordMap, null, 2)};\n\n` +
    `export const SQL_SYSTEM_VARIABLES: readonly SqlKeywordEntry[] = ${JSON.stringify(systemVariables, null, 2)};\n\n` +
    `export const SQL_FUNCTIONS: readonly SqlFunctionEntry[] = ${JSON.stringify(globalFunctions, null, 2)};\n\n` +
    `export const SQL_LIBRARY_MEMBERS: Readonly<Record<string, readonly SqlFunctionEntry[]>> = ${JSON.stringify(libraryMembers, null, 2)};\n`
  );
}

function main() {
  fs.mkdirSync(path.dirname(TS_OUT_PATH), { recursive: true });
  const out = buildSqlCatalogTs();
  fs.writeFileSync(TS_OUT_PATH, out, 'utf8');
  console.log(`Generated ${path.relative(ROOT, TS_OUT_PATH)} (${Buffer.byteLength(out, 'utf8')} bytes)`);
}

if (require.main === module) {
  main();
}

module.exports = { buildSqlCatalogTs };
