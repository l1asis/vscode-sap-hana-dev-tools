'use strict';

/**
 * Generates src/sql/sql-catalog.ts (hover, completion and signature help data) from the SQL catalog:
 *   - docs/specs/catalogs/sql-keywords.json     words with a scoped (lexical) role
 *   - docs/specs/catalogs/builtin-functions.json built-in functions and SQLScript library members
 *
 * Keeps runtime SQL/SQLScript IntelliSense 100% dependency-free (pure TypeScript).
 * Spec: docs/specs/SPEC_RULES.md §2.C, docs/specs/diagnostics/sql-intellisense.md.
 *
 *   node scripts/build-sql-catalog.js [--check]
 */

const lib = require('./lib/sql-catalog');

const TS_OUT = 'src/sql/sql-catalog.ts';

const SQL_BUILT_IN_LIBRARIES = [
  {
    name: 'SQLSCRIPT_SYNC',
    fullName: 'SYS.SQLSCRIPT_SYNC',
    description: 'Built-in SQLScript synchronization library (SLEEP_SECONDS, WAIT_SECONDS, mutex/barrier helpers) ([XSA]/[HDI]/[CLOUD]).',
  },
  {
    name: 'SQLSCRIPT_STRING',
    fullName: 'SYS.SQLSCRIPT_STRING',
    description: 'Built-in SQLScript string formatting, splitting, and table summary library ([XSC]/[XSA]/[HDI]/[CLOUD]).',
  },
  {
    name: 'SQLSCRIPT_PRINT',
    fullName: 'SYS.SQLSCRIPT_PRINT',
    description: 'Built-in SQLScript console print helpers (PRINT_LINE, PRINT_TABLE) ([XSC]/[XSA]/[HDI]/[CLOUD]).',
  },
  {
    name: 'SQLSCRIPT_LOGGING',
    fullName: 'SYS.SQLSCRIPT_LOGGING',
    description: 'Built-in SQLScript structured logging configuration and log writer library ([XSA]/[HDI]/[CLOUD]).',
  },
  {
    name: 'SQLSCRIPT_TEST',
    fullName: 'SYS.SQLSCRIPT_TEST',
    description: 'Built-in SQLScript unit testing assertions and discovery helpers ([XSA]/[HDI]/[CLOUD]).',
  },
];

function classifyKeywordKind(scope) {
  if (scope === 'storage.type.hanasql') return 'type';
  if (scope === 'support.variable.system.hanasql') return 'sysvar';
  if (scope.includes('pragma')) return 'pragma';
  if (scope.startsWith('support.constant.') || scope.startsWith('constant.')) return 'constant';
  if (scope.startsWith('support.function.')) return 'function';
  return 'keyword';
}

function buildSqlCatalogTs(model = lib.loadCatalog()) {
  const keywords = [];
  for (const w of [...model.words.values()].sort((a, b) => a.name.localeCompare(b.name))) {
    const primary = lib.primaryScopedRole(model, w);
    if (!primary) continue; // context-only words are not keywords of their own
    keywords.push({
      name: w.name,
      kind: classifyKeywordKind(primary.scope),
      category: w.roles.includes('reserved') ? 'reserved' : 'non-reserved',
      scope: primary.scope,
      platforms: w.platforms,
    });
  }

  const keywordMap = {};
  const systemVariables = [];
  for (const k of keywords) {
    keywordMap[k.name] = k;
    if (k.kind === 'sysvar') systemVariables.push(k);
  }

  const libraryNames = new Set(SQL_BUILT_IN_LIBRARIES.map((l) => l.name));
  const globalFunctions = [];
  const libraryMembers = {};
  for (const libName of libraryNames) libraryMembers[libName] = [];

  for (const f of model.functions) {
    const sigs = f.signatures;
    const isConstant = sigs.length > 0 && lib.isConstantFunction(f);
    const entry = {
      name: f.name,
      library: f.library,
      category: f.category,
      kind: f.kind || (isConstant ? 'constant' : 'function'),
      ...(f.receiverType ? { receiverType: f.receiverType } : {}),
      platforms: f.platforms || lib.PLATFORMS,
      signatures: sigs,
      ...(f.params && f.params.length
        ? {
            params: f.params.map((p) => ({
              name: p.name,
              ...(p.type ? { type: p.type } : {}),
              ...(p.optional ? { optional: true } : {}),
              ...(p.keyword ? { keyword: p.keyword } : {}),
              description: p.description || '',
            })),
          }
        : {}),
      returnType: f.returnType || 'ANY',
      ...(f.returnDescription ? { returnDescription: f.returnDescription } : {}),
      description: f.description || '',
      ...(isConstant ? { isConstant: true } : {}),
      ...(f.category === 'calculation-engine' ? { deprecatedInCloud: true } : {}),
    };
    if (libraryNames.has(entry.library)) libraryMembers[entry.library].push(entry);
    else globalFunctions.push(entry);
  }

  globalFunctions.sort((a, b) => a.name.localeCompare(b.name));
  for (const libName of Object.keys(libraryMembers)) libraryMembers[libName].sort((a, b) => a.name.localeCompare(b.name));

  const header =
    '// Generated by scripts/build-sql-catalog.js from docs/specs/catalogs/\n' +
    '// (sql-keywords.json + builtin-functions.json). Do not hand-edit; run: npm run build:keywords\n\n' +
    "export type SqlKeywordKind = 'keyword' | 'type' | 'constant' | 'sysvar' | 'pragma' | 'function';\n\n" +
    'export interface SqlKeywordEntry {\n' +
    '  readonly name: string;\n' +
    '  readonly kind: SqlKeywordKind;\n' +
    '  readonly category: string;\n' +
    '  readonly scope: string;\n' +
    '  readonly platforms: readonly string[];\n' +
    '}\n\n' +
    "export type SqlPlatform = 'XSC' | 'XSA' | 'HDI' | 'CLOUD';\n\n" +
    'export type SqlFunctionKind =\n' +
    "  | 'function'\n" +
    "  | 'aggregate'\n" +
    "  | 'window'\n" +
    "  | 'table-function'\n" +
    "  | 'procedure'\n" +
    "  | 'method'\n" +
    "  | 'constructor'\n" +
    "  | 'constant'\n" +
    "  | 'niladic';\n\n" +
    'export interface SqlFunctionParamDoc {\n' +
    '  readonly name: string;\n' +
    '  readonly type?: string;\n' +
    '  readonly optional?: boolean;\n' +
    '  /** Clause keyword that introduces the argument (`SOURCE`, `AS`, `FROM`, `RETURNING`); absent for positional arguments. */\n' +
    '  readonly keyword?: string;\n' +
    '  readonly description: string;\n' +
    '}\n\n' +
    'export interface SqlFunctionEntry {\n' +
    '  readonly name: string;\n' +
    '  readonly library: string;\n' +
    '  /** `builtin-functions.json` category (`aggregate`, `string`, `spatial`, `graphscript`, ...). */\n' +
    '  readonly category: string;\n' +
    '  readonly kind: SqlFunctionKind;\n' +
    '  /** Type a method is called on (`<geometry>.ST_Area()`). */\n' +
    '  readonly receiverType?: string;\n' +
    '  readonly platforms: readonly SqlPlatform[];\n' +
    '  readonly signatures: readonly string[];\n' +
    '  readonly params?: readonly SqlFunctionParamDoc[];\n' +
    '  readonly returnType: string;\n' +
    '  readonly returnDescription?: string;\n' +
    '  readonly description: string;\n' +
    '  readonly isConstant?: boolean;\n' +
    '  readonly deprecatedInCloud?: boolean;\n' +
    '}\n\n' +
    'export interface SqlBuiltinLibraryInfo {\n' +
    '  readonly name: string;\n' +
    '  readonly fullName: string;\n' +
    '  readonly description: string;\n' +
    '}\n\n';

  return (
    header +
    `export const SQL_BUILT_IN_LIBRARIES: readonly SqlBuiltinLibraryInfo[] = ${JSON.stringify(SQL_BUILT_IN_LIBRARIES, null, 2)};\n\n` +
    `export const SQL_KEYWORD_ENTRIES: readonly SqlKeywordEntry[] = ${JSON.stringify(keywords, null, 2)};\n\n` +
    `export const SQL_KEYWORDS_MAP: Readonly<Record<string, SqlKeywordEntry>> = ${JSON.stringify(keywordMap, null, 2)};\n\n` +
    `export const SQL_SYSTEM_VARIABLES: readonly SqlKeywordEntry[] = ${JSON.stringify(systemVariables, null, 2)};\n\n` +
    `export const SQL_FUNCTIONS: readonly SqlFunctionEntry[] = ${JSON.stringify(globalFunctions, null, 2)};\n\n` +
    `export const SQL_LIBRARY_MEMBERS: Readonly<Record<string, readonly SqlFunctionEntry[]>> = ${JSON.stringify(libraryMembers, null, 2)};\n`
  );
}

function buildSqlCatalogOutputs(model) {
  return { [TS_OUT]: buildSqlCatalogTs(model) };
}

function main() {
  const { syncOutputs } = require('./build-keywords');
  const check = process.argv.includes('--check');
  const stale = syncOutputs(buildSqlCatalogOutputs(), check);
  if (check && stale.length) {
    console.error(`Stale generated files (run npm run build:keywords):\n  ${stale.join('\n  ')}`);
    process.exit(1);
  }
  console.log(`${TS_OUT}: ${stale.length ? 'written' : 'up to date'}`);
}

if (require.main === module) main();

module.exports = { buildSqlCatalogTs, buildSqlCatalogOutputs };
